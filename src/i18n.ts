const DICTIONARIES: Record<Language, Record<MessageKey, string>> = { zh, en };

let current: Language = "zh";

export function setLanguage(language: Language): void {
  current = language === "en" ? "en" : "zh";
}

export function getLanguage(): Language {
  return current;
}

/** Pick the dictionary from an Obsidian locale string such as `zh-cn`. */
export function detectLanguage(locale: string | undefined): Language {
  return locale && !locale.toLowerCase().startsWith("zh") ? "en" : "zh";
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = DICTIONARIES[current][key] ?? zh[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}
